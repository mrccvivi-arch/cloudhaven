// Meet the deck edge at full height and keep the segment inside its apron level.
// The visible treads and the collision ramp use the same profile.
for (const stair of s2.stairs) {
  const { a, b, width } = stair;
  const dx = b[0] - a[0], dz = b[2] - a[2];
  const length = Math.hypot(dx,dz);
  const overlaps = (deck, t) => [-.49,0,.49].some(side =>
    inside(deck.outline, a[0]+dx*t + dz/length*width*side, a[2]+dz*t - dx/length*width*side));
  const apron = (point, toward) => {
    const deck = s2.decks.find(d => d.y === point[1] && inside(d.outline,point[0],point[2]));
    if (!deck) return toward > 0 ? 0 : 1;
    let t = toward > 0 ? 0 : 1;
    while (t > -.001 && t < 1.001 && overlaps(deck,t)) t += toward*.0025;
    return t;
  };
  stair.start = Math.max(0, apron(a,1));
  stair.end = Math.min(1, apron(b,-1));
}

